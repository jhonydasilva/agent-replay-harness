"""Measure offline replay, injection, and fake-agent baseline; generate RESULTS.md."""

import argparse
import hashlib
import json
import platform
import statistics
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path
from time import perf_counter_ns
from typing import Any, Callable

from examples.demo_agent import INPUT_TEXT
from examples.fake_llm import FakeLLM
from examples.fake_tools import FakeTools
from src.agent import DemoAgent
from src.comparator import normalized_decisions
from src.recorder import Recorder
from src.replayer import Replayer
from src.trace_schema import read_trace

ROOT = Path(__file__).resolve().parents[1]
SCENARIOS = ("retry", "fallback", "fail_fast")
EXPECTED = {"retry": "success", "fallback": "success", "fail_fast": "failure"}


def timed(operation: Callable[[], Any]) -> tuple[Any, float]:
    start = perf_counter_ns()
    value = operation()
    return value, (perf_counter_ns() - start) / 1_000_000


def describe(samples: list[float]) -> dict[str, float]:
    ordered = sorted(samples)
    p95 = ordered[max(0, ((95 * len(ordered) + 99) // 100) - 1)]
    return {"median": statistics.median(samples), "p95": p95, "max": max(samples)}


def benchmark(count: int) -> dict[str, Any]:
    baseline_path = ROOT / "examples/traces/success.json"
    baseline = read_trace(baseline_path)
    faults = {
        name: json.loads((ROOT / f"examples/faults/{name}.json").read_text(encoding="utf-8"))
        for name in SCENARIOS
    }
    assert normalized_decisions(baseline), "baseline must have recorded agent decisions"
    direct_times: list[float] = []
    replay_times: list[float] = []
    injection_times: dict[str, list[float]] = defaultdict(list)
    counts: Counter[str] = Counter()
    successes: Counter[str] = Counter()
    deliberate_diffs: Counter[str] = Counter()
    all_decisions_identical = 0
    total_decisions = 0
    expected_decisions = normalized_decisions(baseline)

    for _ in range(count):
        def direct():
            recorder = Recorder(FakeLLM(), FakeTools(), INPUT_TEXT)
            outcome = DemoAgent().run(INPUT_TEXT, recorder)
            return outcome, recorder.trace

        (outcome, _), duration = timed(direct)
        assert outcome == "success"
        direct_times.append(duration)

        result, duration = timed(lambda: Replayer(baseline).execute())
        replay_times.append(duration)
        observed = normalized_decisions(result.trace)
        total_decisions += len(expected_decisions)
        all_decisions_identical += sum(
            before == after for before, after in zip(expected_decisions, observed)
        )
        successes["strict"] += int(result.comparison["identical"] and result.outcome == "success")

    for index in range(count):
        scenario = SCENARIOS[index % len(SCENARIOS)]
        counts[scenario] += 1
        result, duration = timed(lambda: Replayer(baseline, fault=faults[scenario]).execute())
        injection_times[scenario].append(duration)
        successes[scenario] += int(result.outcome == EXPECTED[scenario])
        deliberate_diffs[scenario] += int(
            not result.comparison["identical"]
            and result.comparison["first_divergence"]["decision_index"] == 2
        )

    return {
        "count": count,
        "measured_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "python": platform.python_version(),
        "platform": f"{platform.system()} {platform.machine()}",
        "trace_sha256": hashlib.sha256(baseline_path.read_bytes()).hexdigest(),
        "baseline_decisions": len(expected_decisions),
        "strict_matching_runs": successes["strict"],
        "strict_matching_decisions": all_decisions_identical,
        "total_decisions": total_decisions,
        "direct": describe(direct_times),
        "replay": describe(replay_times),
        "scenarios": [
            {
                "name": scenario,
                "count": counts[scenario],
                "expected": EXPECTED[scenario],
                "matched_outcome": successes[scenario],
                "divergence": deliberate_diffs[scenario],
                "time": describe(injection_times[scenario]),
            }
            for scenario in SCENARIOS
        ],
    }


def render_markdown(result: dict[str, Any]) -> str:
    count = result["count"]
    matching = result["strict_matching_runs"]
    decision_total = result["total_decisions"]
    decision_match = result["strict_matching_decisions"]
    rows = [
        "# Measured results",
        "",
        "> Generated by `python -m benchmarks.run_benchmarks`. Do not edit numbers manually.",
        "",
        f"- Measured at (UTC): `{result['measured_at']}`",
        f"- Environment: Python `{result['python']}`, `{result['platform']}`",
        f"- Source trace SHA-256: `{result['trace_sha256']}`",
        f"- Recorded baseline decisions per execution: **{result['baseline_decisions']}**",
        f"- Strict replay runs with all decisions identical: **{matching}/{count} "
        f"({matching / count * 100:.2f}%)**",
        f"- Normalized decisions identical: **{decision_match}/{decision_total} "
        f"({decision_match / decision_total * 100:.2f}%)**",
        "",
        "## Timing (milliseconds)",
        "",
        "| Execution path | Runs | Median | P95 | Maximum |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, metric in (
        ("Direct fake-agent recording", "direct"),
        ("Strict trace replay", "replay"),
    ):
        times = result[metric]
        rows.append(
            f"| {name} | {count} | {times['median']:.3f} | "
            f"{times['p95']:.3f} | {times['max']:.3f} |"
        )
    rows.extend(
        [
            "",
            "## Controlled fault scenarios",
            "",
            "| Scenario | Runs | Expected outcome matched | Intentional divergences detected | "
            "Median (ms) | Maximum (ms) |",
            "|---|---:|---:|---:|---:|---:|",
        ]
    )
    for scenario in result["scenarios"]:
        rows.append(
            f"| `{scenario['name']}` ({scenario['expected']}) | {scenario['count']} | "
            f"{scenario['matched_outcome']}/{scenario['count']} | "
            f"{scenario['divergence']}/{scenario['count']} | "
            f"{scenario['time']['median']:.3f} | {scenario['time']['max']:.3f} |"
        )
    rows.extend(
        [
            "",
            "## Methodology and limits",
            "",
            f"- Ran {count} direct fake-agent recordings, {count} strict replays, "
            f"and {count} injected replays, sequentially in one process.",
            "- Injection runs were distributed round-robin across retry, fallback, and fail-fast.",
            "- Timings use `time.perf_counter_ns()` around each execution, including trace "
            "creation and comparison, excluding disk writes and process startup.",
            "- P95 uses the nearest-rank method; outcomes are verified per run.",
            "- The direct baseline is a local fake agent, **not** a paid or live LLM call.",
            "- Strict replay consumes recorded LLM and tool responses; injected branches use "
            "local fixture responses. This does not establish production reliability.",
            "- Observed results apply to this single scenario and environment, not to arbitrary "
            "agent inputs, new LLM decisions, concurrency, or live external services.",
            "",
        ]
    )
    return "\n".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", type=int, default=100, help="number of strict and fault runs")
    parser.add_argument("--output", default="RESULTS.md", help="generated results file")
    args = parser.parse_args()
    if args.runs < len(SCENARIOS):
        parser.error(f"--runs must be at least {len(SCENARIOS)}")
    stats = benchmark(args.runs)
    output = Path(args.output)
    if not output.is_absolute():
        output = ROOT / output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_markdown(stats), encoding="utf-8")
    print(
        f"Benchmark: strict={stats['strict_matching_runs']}/{args.runs}, "
        f"decisions={stats['strict_matching_decisions']}/{stats['total_decisions']}; "
        f"faults={sum(s['divergence'] for s in stats['scenarios'])}/{args.runs}; "
        f"wrote {output}"
    )


if __name__ == "__main__":
    main()
